def fmt(n):
    return f"{n:,}"


def rprice(lo, hi):
    span = hi - lo
    if hi <= 3_000:
        step = 250
    elif hi <= 50_000:
        step = 1_000
    elif hi <= 500_000:
        step = 5_000
    else:
        step = 25_000
    return lo + step * random.randint(0, max(1, span // step))


def ch(*options):
    return random.choice(options)


def pick_goods():
    return random.choice(ALL_GOODS)


def gsel(g, m, f):
    """اختيار الصيغة حسب جنس المنتج: gsel(g, 'خذه', 'خذها')"""
    return m if g == "m" else f


def pick_pair(*groups):
    """كل مجموعة = (قائمة أسئلة، قائمة أجوبة مطابقة بالمعنى) — نختار المجموعة
    أولاً ثم سؤالاً وجواباً منها حتى يظل الجواب على نفس موضوع السؤال."""
    qs, ans = random.choice(groups)
    return random.choice(qs), random.choice(ans)


def wrap(q, a, g="m", ask=True):
    """إضافة مقدمة وخاتمة بشرية للسؤال والجواب."""
    qp = random.choice(Q_PREFIX_ASK if ask else Q_PREFIX_TALK)
    qt = random.choice(Q_TAIL).replace("{o}", gsel(g, "ه", "ها"))
    ap = random.choice(A_PREFIX)
    at = random.choice(A_TAIL)
    # لا نكرر تحية إذا السؤال أصلاً يبدأ بنداء مشابه
    if qp and q[:3] in ("هلا", "الل", "لو ", "صبا", "مسا"):
        qp = ""
    if ap and a[:3] in ("هلا", "حيا", "تدل", "على", "أهل"):
        ap = ""
    return qp + q + qt, ap + a + at


def formality_of(q, default=("Casual", "informal")):
    if any(w in q for w in ("لو سمحت", "إذا ممكن", "بلا زحمة")):
        return ch("Polite", "Polite", "formal")
    if any(w in q for w in ("ولك", "يمعود", "يابه")):
        return "informal"
    return random.choice(default)


