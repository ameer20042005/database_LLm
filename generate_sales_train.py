def pick_pair(*groups):
    """كل مجموعة = (قائمة أسئلة، قائمة أجوبة مطابقة بالمعنى) — نختار المجموعة
    أولاً ثم سؤالاً وجواباً منها حتى يظل الجواب على نفس موضوع السؤال."""
    qs, ans = random.choice(groups)
    return random.choice(qs), random.choice(ans)


