def fmt(n):
    return f"{n:,}"


def rprice(lo, hi):
    span = hi - lo
    if hi <= 3_000:
        step = 250
    elif hi <= 50_000:
        step = 1_000
    elif hi <= 500_000:
        step = 5_000
    else:
        step = 25_000
    return lo + step * random.randint(0, max(1, span // step))


