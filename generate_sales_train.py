def main():
    seen = set()
    q_count = {}
    a_count = {}
    rows = []
    attempts = 0
    while len(rows) < TARGET and attempts < TARGET * 600:
        attempts += 1
        fn = random.choices(FUNCS, weights=WEIGHTS, k=1)[0]
        q, a, topic, formality = fn()
        key = (q, a)
        if key in seen:
            continue
        # سقف التكرار الحرفي للسؤال أو الجواب الواحد
        if q_count.get(q, 0) >= MAX_REPEAT or a_count.get(a, 0) >= MAX_REPEAT:
            continue
        seen.add(key)
        q_count[q] = q_count.get(q, 0) + 1
        a_count[a] = a_count.get(a, 0) + 1
        rows.append({
            "Question": q,
            "Answer": a,
            "Topic": topic,
            "Formality": formality,
            "Dialect": "Iraqi Arabic",
            "Date": rdate(),
        })
    if len(rows) < TARGET:
        raise SystemExit(f"ما وصلنا للهدف: {len(rows)} من {TARGET}")
    with open(OUT, "w", encoding="utf-8") as f:
        json.dump(rows, f, ensure_ascii=False, indent=2)
    print(f"تم توليد {len(rows)} محادثة مبيعات -> {OUT}")


if __name__ == "__main__":
    main()
