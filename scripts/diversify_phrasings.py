# علامات تمنع الاستبدال — أي رد فيها يُترك كما هو
FORBIDDEN = ("[TOOL_CALL]", "[ORDER_READY]", "{", "}", "[TOOL_RESULT]")


def should_skip(text):
    """الأرقام مؤسَّسة بالكتالوج — أي رد فيه رقم يبقى حرفياً."""
    if any(f in text for f in FORBIDDEN):
        return True
    return any(ch.isdigit() for ch in text)


def main():
    files = sorted(DATA.glob("iraqi_train_v8_part*.jsonl"))
    assert files, "ملفات v8 غير موجودة"

    BACKUP.mkdir(exist_ok=True)
    for f in files:
        if not (BACKUP / f.name).exists():
            shutil.copy2(f, BACKUP / f.name)
    print(f"✅ نسخة احتياطية بـ{BACKUP.name}/")

    stats = Counter()
    before_texts, after_texts = [], []

    for f in files:
        rows = [json.loads(l) for l in f.open(encoding="utf-8")]
        for r in rows:
            # بذرة مربوطة بالمحادثة → النتيجة ثابتة عند إعادة التشغيل،
            # ومحادثتان مختلفتان تاخذان بديلين مختلفين
            seed = hash(json.dumps(r["messages"], ensure_ascii=False,
                                   sort_keys=True)) & 0xFFFFFFFF
            rng = random.Random(seed)
            for t in r["messages"]:
                if t["role"] != "assistant":
                    continue
                txt = t["content"]
                before_texts.append(txt)
                g = TRIGGER_MAP.get(txt.strip())
                if g and not should_skip(txt):
                    new = rng.choice(GROUPS[g]["variants"])
                    if new != txt:
                        t["content"] = new
                        stats[g] += 1
                after_texts.append(t["content"])
        with f.open("w", encoding="utf-8") as fh:
            for r in rows:
                fh.write(json.dumps(r, ensure_ascii=False) + "\n")

    # ════════════════════════ التقرير ════════════════════════
    b, a = Counter(before_texts), Counter(after_texts)
    n = len(before_texts)
    print(f"\n{'المجموعة':<26}{'مُستبدَل':>10}{'صيغ':>7}")
    for g, c in stats.most_common():
        print(f"  {g:<24}{c:>10,}{len(GROUPS[g]['variants']):>7}")
    print(f"  {'المجموع':<24}{sum(stats.values()):>10,}")

    print(f"\n{'':<26}{'قبل':>12}{'بعد':>12}")
    print(f"  {'ردود المساعد':<24}{n:>12,}{n:>12,}")
    print(f"  {'جمل مختلفة':<24}{len(b):>12,}{len(a):>12,}")
    print(f"  {'نسبة التنوع':<24}{100*len(b)/n:>11.1f}%{100*len(a)/n:>11.1f}%")
    print(f"  {'أعلى جملة':<24}{b.most_common(1)[0][1]:>12,}"
          f"{a.most_common(1)[0][1]:>12,}")
    top30_b = sum(x for _, x in b.most_common(30))
    top30_a = sum(x for _, x in a.most_common(30))
    print(f"  {'حصة أعلى 30':<24}{100*top30_b/n:>11.1f}%{100*top30_a/n:>11.1f}%")

    print("\nأكثر خمس جمل بعد التنويع:")
    for s, c in a.most_common(5):
        print(f"  {c:>5,}×  {s[:60]}")
    print(f"\n↩️ للتراجع: انسخ {BACKUP.name}/*.jsonl فوق data/")


if __name__ == "__main__":
    main()
