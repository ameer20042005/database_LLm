def _expand(gname, base):
    """يضرب المحاور على الصيغ الأساس بقواعد تحمي السلامة اللغوية.

    الضرب الأعمى ينتج ركاكة: «تدلل الله يبارك فيك، تفضل بالسلامة
    ونورتنا صدگني» — ثلاث خواتم متراكمة بلا معنى. القواعد أدناه
    مستخلصة من تدقيق فعلي على عينة:

      • **خاتمة واحدة بالأكثر**: إما ذيل أو لاحقة، مو الاثنين. تراكم
        التوكيدات («صدگني والله عيني») مو عراقي، هو حشو آلي.
      • **صفر افتتاحية على جملة تبدأ بتوكيد** («والله ماكو...») —
        «صدگني والله ماكو» تكرار للتوكيد نفسه.
      • **صفر افتتاحية على جملة طويلة** (>7 كلمات) — تصير ثقيلة.
      • الجملة الاستفهامية ما تاخذ ذيلاً بعد «؟».
      • صفر تكرار لأي كلمة توكيد بين المحاور.
    """
    # التوكيد والنداء يُعاملان سواءً: تراكمهما هو مصدر الركاكة.
    # «خويه تدلل عيني» فيها ثلاث مناداات، و«الله يخليك تدلل أي وقت»
    # افتتاحية دعائية على جملة أصلاً فيها نداء.
    ASSERT_W = ("والله", "صدگني", "صدگ", "عيني", "خويه", "ترة", "بصراحة",
                "تدلل", "شوف", "يخليك", "الله")
    out = set(base)
    tails = TAILS.get(gname, [""])
    for v in base:
        vs = v.strip()
        q = vs.endswith("؟")
        long_v = len(vs.split()) > 7
        v_words = set(vs.replace("،", " ").split())
        # الجملة اللي أصلاً فيها أي توكيد/نداء ما تاخذ افتتاحية إطلاقاً
        has_assert = bool(v_words & set(ASSERT_W))

        for op in OPENERS:
            ow = op.strip()
            if ow and (long_v or has_assert):
                continue
            for tl in (tails if not q else [""]):
                tw = set(tl.replace("،", " ").split())
                if tw & v_words:
                    continue
                # ذيل توكيدي على جملة فيها توكيد = تراكم
                if (tw & set(ASSERT_W)) and has_assert:
                    continue
                # ── خاتمة واحدة بالأكثر ──
                cl_opts = [""] if (tl.strip() or q) else CLOSERS
                for cl in cl_opts:
                    cw = cl.strip()
                    if cw and (cw in v_words or cw == ow or has_assert):
                        continue
                    s = " ".join((op + vs + tl + cl).split())
                    # حارس أخير: صفر توكيدين متجاورين
                    parts = s.split()
                    if any(parts[i] in ASSERT_W and parts[i + 1] in ASSERT_W
                           for i in range(len(parts) - 1)):
                        continue
                    out.add(s)
    return sorted(out)


