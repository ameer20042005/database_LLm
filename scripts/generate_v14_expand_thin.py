def gen_v8_thin(per_cat=340):
    """يولّد بأسماء فئات v8 نفسها. النصف الأول بلا system والثاني معه —
    الفئات الأصلية بـv8 موجودة بالصيغتين (`greetings` و`greetings_sys`)."""
    out = []
    names = list(V8_THIN)
    for cat, pairs in V8_THIN.items():
        for n in range(per_cat):
            i = random.randrange(len(pairs))
            q, a = pairs[i]
            use_sys = n % 2 == 1
            msgs = []
            if use_sys:
                msgs.append({"role": "system", "content": CHAT_SYS})
            msgs += [{"role": "user", "content": q},
                     {"role": "assistant", "content": a}]
            # المتابعة من أي مجموعة — يكسر سقف n×(n−1) ويشبه الحچي الطبيعي
            p2 = V8_THIN[random.choice(names)]
            q2, a2 = random.choice(p2)
            if q2 != q:
                msgs += [{"role": "user", "content": q2},
                         {"role": "assistant", "content": a2}]
            if random.random() < 0.4:
                p3 = V8_THIN[random.choice(names)]
                q3, a3 = random.choice(p3)
                if q3 not in (q, q2):
                    msgs += [{"role": "user", "content": q3},
                             {"role": "assistant", "content": a3}]
            out.append(_row(cat + ("_sys" if use_sys else ""), msgs))
    return out


