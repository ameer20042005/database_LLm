def _sys(ps):
    # استبدال مباشر لا .format() — القالب فيه أقواس JSON حرفية
    cat, alias, _, _d = ps
    return (EXTRACT_SYS.replace("{catalog}", "\n".join("- " + p for p in cat))
                       .replace("{aliases}", alias))


def _j(items, install):
    return json.dumps({"items": items, "install": install},
                      ensure_ascii=False, separators=(",", ":"))


def _row(cat, msgs):
    return {"messages": msgs, "category": cat, "dialect": "iraqi_arabic",
            "source_file": SOURCE}


def gen_items(per_cat=170):
    """المحاور تُسحب عشوائياً ومستقلة عن بعضها. ربطها كلها بعدّاد واحد
    (ci) يجعلها تدور بتزامن فتتكرر التوليفات — وهذا ينتج نسخاً متطابقة
    بدل التنوع المقصود. العشوائية هنا مع seed ثابت تحفظ التكرارية."""
    out = []
    for _ in range(per_cat):
        for kind in ("numword", "partial_name", "install_flag", "dual_form",
                     "correction", "foreign_ignored", "multi_sentence"):
            ps = random.choice(PRODUCT_SETS)
            cat, _, alias_words, dual_words = ps
            idx = random.randrange(2)
            name, alias = cat[idx], alias_words[idx]
            qty = random.randint(1, 6)
            ask = random.choice(ASK)
            pol = random.choice(POLITE)
            inst = random.random() < 0.4
            tail = (random.choice(INSTALL_YES) if inst
                    else random.choice(INSTALL_NO))

            if kind == "numword":
                w = random.choice(NUMWORDS[qty])
                u = f"{ask} {w} {alias} {pol} {tail}"
                a = _j([{"name": name, "qty": qty}], inst)
            elif kind == "partial_name":
                u = f"{pol} {ask} {alias}، {random.choice(NUMWORDS[qty])} {tail}"
                a = _j([{"name": name, "qty": qty}], inst)
            elif kind == "install_flag":
                inst = random.random() < 0.5
                tail = (random.choice(INSTALL_YES) if inst
                        else random.choice(INSTALL_NO))
                u = f"{ask} {qty} {alias} {tail}"
                a = _j([{"name": name, "qty": qty}], inst)
            elif kind == "dual_form":
                # صيغة المثنى العربية: «مكيفين» = 2 بلا رقم صريح.
                # المثنى مكتوب صراحةً بالبيانات لا مُشتقاً بلصق «ين» —
                # الاشتقاق الآلي ينتج «نشافةين» و«55ين» وهي مو عربية.
                dual = dual_words[idx]
                u = f"{ask} {dual} {pol} {tail}"
                a = _j([{"name": name, "qty": 2}], inst)
            elif kind == "correction":
                q2 = random.choice([x for x in range(1, 6) if x != qty])
                fix = random.choice(["لحظة غيرت رأيي خليهن",
                                     "لا لا، خليها", "عفواً قصدي",
                                     "صحح الطلب خليه"])
                u = f"{ask} {random.choice(NUMWORDS[qty])} من {alias}، {fix} {q2}"
                a = _j([{"name": name, "qty": q2}], inst)
            elif kind == "foreign_ignored":
                f = random.choice(FOREIGN)
                join = random.choice(["ويا", "و", "مع"])
                u = f"{ask} {qty} {alias} {join} {f}"
                a = _j([{"name": name, "qty": qty}], inst)
            else:  # multi_sentence
                other = cat[1 - idx]
                q2 = random.randint(1, 4)
                u = (f"{random.choice(['مساء الخير','صباح الخير','هلا','السلام عليكم'])}. "
                     f"حاجتي الاولى {alias_words[idx]} عدد {qty}. "
                     f"والثانية {alias_words[1 - idx]} عدد {q2}.")
                a = _j([{"name": name, "qty": qty},
                        {"name": other, "qty": q2}], inst)

            u = " ".join(u.split())
            out.append(_row("items_" + kind,
                            [{"role": "system", "content": _sys(ps)},
                             {"role": "user", "content": u},
                             {"role": "assistant", "content": a}]))
    return out


