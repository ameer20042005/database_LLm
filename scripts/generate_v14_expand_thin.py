def main():
    rows = gen_items() + gen_qa_expand() + gen_v8_thin()

    key = lambda m: json.dumps(m, ensure_ascii=False, sort_keys=True)
    seen, uniq = set(), []
    for r in rows:
        k = key(r["messages"])
        if k not in seen:
            seen.add(k)
            uniq.append(r)
    dropped = len(rows) - len(uniq)
    rows = uniq

    # صفر تداخل مع أي ملف قائم
    existing = set()
    for f in DATA.glob("*.jsonl"):
        if f.name.startswith("iraqi_v14"):
            continue
        for line in f.open(encoding="utf-8"):
            try:
                existing.add(key(json.loads(line)["messages"]))
            except Exception:
                pass
    before = len(rows)
    rows = [r for r in rows if key(r["messages"]) not in existing]

    random.shuffle(rows)
    out = DATA / "iraqi_v14_expand.jsonl"
    with out.open("w", encoding="utf-8") as fh:
        for r in rows:
            fh.write(json.dumps(r, ensure_ascii=False) + "\n")

    c = Counter(r["category"] for r in rows)
    print(f"✅ {out.name}: {len(rows):,} مثال جديد")
    print(f"   (حُذف {dropped:,} مكرر داخلياً، و{before - len(rows):,} متداخل مع ملفات قائمة)")
    print(f"\n{'الفئة':<34}{'جديد':>8}")
    for k, v in c.most_common():
        print(f"  {k:<32}{v:>8,}")


if __name__ == "__main__":
    main()
