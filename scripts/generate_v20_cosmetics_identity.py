# كل رد: هوية البائع صراحةً + نصيحة بالمختص
IDENTITY_A = [
    "أني متخصص بالمبيعات بس عيني، هاي مو مجالي — {ref}",
    "صراحةً شغلي بيع الأجهزة، ما أفهم بهاي — {ref}",
    "أني بائع عيني، اختصاصي بالبضاعة مو بهيچ أمور — {ref}",
    "والله أني موظف مبيعات، هاي برّه شغلي — {ref}",
    "تخصصي البيع عيني، ما أگدر أفيدك بهاي — {ref}",
    "أني أفهم بالأجهزة والبيع بس، هاي مو اختصاصي — {ref}",
]
BACK_TO_SALES = [
    " — تأمر بشي من المحل؟",
    " — بس إذا تحتاج شي من الأجهزة أني بالخدمة",
    " — وإذا عندك سؤال عن البضاعة تدلل",
    "",
    "",
]


def gen_seller_identity(n):
    out = []
    for _ in range(n):
        (p1, v1), (p2, v2) = random.sample(APPLIANCES, 2)
        sysm = SYS_GEN.format(p1=p1, v1=money(v1), p2=p2, v2=money(v2))
        q, ref = random.choice(OFF_Q)
        ans = random.choice(IDENTITY_A).format(ref=ref) + random.choice(BACK_TO_SALES)
        out.append(rec("off_topic_seller_identity", [
            {"role": "system", "content": sysm},
            {"role": "user", "content": q},
            {"role": "assistant", "content": ans},
        ]))
    return out


# ════════════════════════════════════════════════════════════
def main():
    rows, seen = [], set()
    plan = [(gen_normal_sale, 420), (gen_therapeutic_edge, 240),
            (gen_seller_identity, 420)]
    counts = {}
    for fn, n in plan:
        kept = []
        for r in fn(n * 4):
            if len(kept) >= n:
                break
            k = json.dumps(r["messages"], ensure_ascii=False, sort_keys=True)
            if k in seen:
                continue
            seen.add(k)
            kept.append(r)
        counts[kept[0]["category"]] = len(kept)
        rows.extend(kept)

    random.shuffle(rows)
    p = DATA / "iraqi_v20_cosmetics_identity.jsonl"
    with p.open("w", encoding="utf-8") as fh:
        for r in rows:
            fh.write(json.dumps(r, ensure_ascii=False) + "\n")

    # ── تحقق ──
    REFER_MED = re.compile(r"طبيب|دكتور|صيدلية|مختص")
    SELLER = re.compile(r"متخصص بالمبيعات|بائع|شغلي بيع|تخصصي البيع|موظف مبيعات|أفهم بالأجهزة")
    NUM = re.compile(r"\d[\d,]{2,}")

    sale = [r for r in rows if r["category"] == "cosmetics_sale"]
    bad_sale = sum(1 for r in sale for m in r["messages"]
                   if m["role"] == "assistant" and REFER_MED.search(m["content"]))
    edge = [r for r in rows if r["category"] == "cosmetics_medical_edge"]
    edge_ok = sum(1 for r in edge
                  if any(m["role"] == "assistant" and REFER_MED.search(m["content"])
                         for m in r["messages"])
                  and any(m["role"] == "assistant" and NUM.search(m["content"])
                          for m in r["messages"]))
    ident = [r for r in rows if r["category"] == "off_topic_seller_identity"]
    ident_ok = sum(1 for r in ident
                   if any(m["role"] == "assistant" and SELLER.search(m["content"])
                          for m in r["messages"]))

    print("=" * 62)
    print("v20 — الكوزمتك وهوية البائع")
    print("=" * 62)
    for k, v in counts.items():
        print(f"  {k:<32}{v:>6}")
    print()
    print(f"  {'✅' if not bad_sale else '❌'} بيع كوزمتك بلا إحالة طبية   "
          f"{len(sale)-bad_sale}/{len(sale)}")
    print(f"  {'✅' if edge_ok == len(edge) else '❌'} حالة الحدّ: نصيحة + بيع      "
          f"{edge_ok}/{len(edge)}")
    print(f"  {'✅' if ident_ok == len(ident) else '❌'} الرفض يذكر إنه بائع        "
          f"{ident_ok}/{len(ident)}")
    print(f"\n  📁 {p.name}")


if __name__ == "__main__":
    main()
