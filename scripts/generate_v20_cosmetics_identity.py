"""
v20 — مواد التجميل بضاعة عادية، وهوية البائع بكل رفض.

═══════════════════════════════════════════════════════════════
المسألة الأولى: الكوزمتك بضاعة لا دواء
═══════════════════════════════════════════════════════════════
قاعدة v19 الطبية صارمة عمداً، بس فيها خطر جانبي: كلمات مثل «كريم»
و«غسول» و«سيروم» تقع بمنطقة رمادية بين الدواء والبضاعة. إذا الموديل
عمّم القاعدة الطبية عليها، يصير **يرفض يبيع كريم مرطب** — وهذا خسارة
بيع مباشرة، لا سلامة.

**المقيس على داتا v19:** 181 ذكراً لكلمات تجميل برسائل الزبون، بس
الغالبية العظمى منها **اسم شخص** («مصطفى كريم»، «حجي كريم»، «رمضان
كريم») لا مادة تجميل. يعني **التغطية الفعلية للبيع الكوزمتك ≈ صفر**.

فالموديل ما عنده أمثلة تعلّمه يبيعها طبيعياً، وعنده 924 محادثة طبية
تعلّمه يحيل. النتيجة المتوقعة: إحالة كريم الأساس للصيدلية.

**الحل:** أمثلة بيع كوزمتك عادية تماماً — سعر، كمية، طلب، مساومة —
بلا أي إحالة طبية. مع **حالة الحدّ**: إذا الزبون سأل عن الكوزمتك
لغرض **علاجي** (حساسية، إكزيما، حبوب الوجه)، هناك بس ينصح بمختص
**ويبقى يبيع المنتج** إذا يريده.

═══════════════════════════════════════════════════════════════
المسألة الثانية: هوية البائع بالرفض
═══════════════════════════════════════════════════════════════
**المقيس:** 4,322 رد خارج النطاق، **676 بس (16%)** تذكر إنه بائع أو
إن المحل مالته للأجهزة. الباقي يرفض بلا ما يوضّح **ليش** — «ما إلي
بهاي» أنفع منها «أني متخصص بالمبيعات، هاي مو مجالي».

توضيح الهوية يخدم شيئين: يخلي الرفض مفهوماً لا جافاً، ويفتح باب
الرجوع للبيع طبيعياً.

**القاعدة الجديدة:** كل رفض خارج النطاق يذكر التخصص صراحةً، وينصح
بمراجعة المختص المناسب (طبيب للصحي، مختص/جهة مختصة للباقي).
"""
