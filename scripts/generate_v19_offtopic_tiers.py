def gen_product(n):
    out = []
    kinds = list(MISSING_BY_KIND)
    for _ in range(n):
        sysm, (p1, v1), (p2, v2) = sysmsg()
        # البديل من **نفس فئة** المنتج المفقود إن أمكن — هذا نص الفكرة:
        # اللي يسأل عن ثلاجة ينعرضله ثلاجة، مو غسالة.
        kind = next((k for k in kinds if k in p1), None)
        if kind is None:
            kind = next((k for k in kinds if k in p2), random.choice(kinds))
            alt = p2
        else:
            alt = p1
        m = random.choice(MISSING_BY_KIND[kind])
        out.append({"category": "off_topic_product_alt", "messages": [
            {"role": "system", "content": sysm},
            {"role": "user", "content": random.choice(PROD_Q).format(m=m)},
            {"role": "assistant",
             "content": random.choice(PROD_A).format(m=m, alt=alt)},
        ]})
    return out


# ════════════════════════════════════════════════════════════
def main():
    rows, seen = [], set()
    plan = [(gen_medical, 700), (gen_general, 300), (gen_product, 300)]
    counts = {}
    for fn, n in plan:
        kept = []
        for r in fn(int(n * 3)):
            if len(kept) >= n:
                break
            k = json.dumps(r["messages"], ensure_ascii=False, sort_keys=True)
            if k in seen:
                continue
            seen.add(k)
            kept.append(r)
        counts[kept[0]["category"]] = len(kept)
        rows.extend(kept)

    random.shuffle(rows)
    p = DATA / "iraqi_v19_offtopic_tiers.jsonl"
    with p.open("w", encoding="utf-8") as fh:
        for r in rows:
            fh.write(json.dumps(r, ensure_ascii=False) + "\n")

    # ── تحقق صارم على الطبقة الطبية ──
    NUM = re.compile(r"\d")
    DOC = re.compile(r"دكتور|طبيب|صيدلي|صيدلية|عيادة|مستشفى|مختص")
    med = [r for r in rows if r["category"] == "off_topic_medical_strict"]
    bad_num = bad_doc = bad_prod = 0
    for r in med:
        prods = [n for c in CATALOGS for n, _ in c]
        for m in r["messages"]:
            if m["role"] != "assistant":
                continue
            if NUM.search(m["content"]):
                bad_num += 1
            if any(pn in m["content"] for pn in prods):
                bad_prod += 1
        last = [m for m in r["messages"] if m["role"] == "assistant"][-1]
        if not DOC.search(last["content"]):
            bad_doc += 1

    print("=" * 62)
    print("v19 — طبقات «خارج النطاق»")
    print("=" * 62)
    for k, v in counts.items():
        print(f"  {k:<32}{v:>6}")
    print(f"\n  الطبقة الطبية — فحص صارم ({len(med)} محادثة):")
    print(f"    {'✅' if not bad_num else '❌'} صفر رقم بالرد          {bad_num}")
    print(f"    {'✅' if not bad_prod else '❌'} صفر اقتراح منتج        {bad_prod}")
    print(f"    {'✅' if not bad_doc else '❌'} إحالة بآخر رد          {bad_doc} بلا إحالة")
    print(f"\n  📁 {p.name}")


if __name__ == "__main__":
    main()
