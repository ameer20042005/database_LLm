SYS = """أنت موظف مبيعات بمحل عراقي.

الموجود حالياً:
- {p1}: {v1} دينار
- {p2}: {v2} دينار

انسخ الأسعار والأسماء حرفياً من القائمة. أي شي مو بالقائمة گله ماكو عدنا.
إذا سألك الزبون عن أمور صحية أو طبية (وجع، دواء، أعراض، جرعة) — لا تنصحه أبداً ولا تقترح عليه منتج، وجّهه للطبيب أو الصيدلية."""


def money(n):
    return f"{n:,}"


def sysmsg():
    (p1, v1), (p2, v2) = random.choice(CATALOGS)
    return SYS.format(p1=p1, v1=money(v1), p2=p2, v2=money(v2)), (p1, v1), (p2, v2)


