NUM = re.compile(r"[\d،,]{3,}")
MARKERS = ["عيني", "خويه", "خوية", "هواي", "شلون", "صدگ", "ماكو", "اكو",
           "هسه", "زين", "والله", "حبيبي", "شكو", "گول", "چان", "حياك"]


def validate(rows):
    errs = Counter()
    for r in rows:
        cat, msgs = r["category"], r["messages"]
        sysm = " ".join(m["content"] for m in msgs if m["role"] == "system")
        asst = [m["content"] for m in msgs if m["role"] == "assistant"]

        if cat.startswith("order_total_clean_promise"):
            # كل رقم بالنظام + الرد الأخير (الوعد) بلا أي رقم إطلاقاً
            for tok in NUM.findall(asst[-1]):
                errs["رقم برد الوعد النظيف"] += 1
            # دور الفرق (٢ صنف بس بالمحادثة المرکّبة) رقم مشتق حسابياً،
            # مو مخترع — نتجاهله ونتحقق من بقية الأدوار فقط
            diff_idx = 2 if cat == "order_total_clean_promise" else -1
            for i, a in enumerate(asst[:-1]):
                if i == diff_idx:
                    continue
                for tok in NUM.findall(a):
                    if tok not in sysm:
                        errs["رقم مو بالكتالوج"] += 1

        if cat.startswith("casual_dialect_dense"):
            full = " ".join(asst)
            found = sum(full.count(m) for m in MARKERS)
            if found < 3:
                errs["أقل من 3 ماركرات بالمحادثة"] += 1
    return errs


def main():
    rows, seen, counts = [], set(), {}
    for fn, n in PLAN:
        kept = []
        for r in fn(n * 6):
            if len(kept) >= n:
                break
            k = json.dumps(r["messages"], ensure_ascii=False, sort_keys=True)
            if k in seen:
                continue
            seen.add(k)
            kept.append(r)
        counts[kept[0]["category"]] = len(kept)
        rows.extend(kept)

    errs = validate(rows)
    random.shuffle(rows)
    p = DATA / "iraqi_v28_promise_dialect.jsonl"
    with p.open("w", encoding="utf-8") as fh:
        for r in rows:
            fh.write(json.dumps(r, ensure_ascii=False) + "\n")

    print("=" * 62)
    print("v28 — وعد الحساب النظيف + كثافة اللهجة بالكلام الاجتماعي")
    print("=" * 62)
    for k, v in counts.items():
        print(f"  {k:<32}{v:>6}")
    print(f"  {'المجموع':<32}{len(rows):>6}")
    print()
    if errs:
        print("  ❌ أخطاء تحقق:")
        for k, v in errs.most_common():
            print(f"     {k:<44}{v:>5}")
    else:
        print(f"  ✅ التحقق نظيف على {len(rows)} مثالاً")
    print(f"  📁 {p.name}")


if __name__ == "__main__":
    main()
