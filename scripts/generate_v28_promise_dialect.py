def gen_direct_clean_promise(n):
    """دور واحد: طلب مرکّب مباشر بلا سياق سابق، بس نفس الوعد النظيف."""
    out = []
    for _ in range(n):
        a, va, b, vb, label = random.choice(PAIRS)
        sysm = build_system(a, va, b, vb)
        p = random.choice([a, b])
        qty = random.choice([2, 3, 4])
        msgs = [
            {"role": "system", "content": sysm},
            {"role": "user",
             "content": random.choice(DIRECT_Q).format(qty=qty, p=p)},
            {"role": "assistant", "content": random.choice(CLEAN_PROMISE)},
        ]
        out.append(rec("order_total_clean_promise_short", msgs))
    return out


