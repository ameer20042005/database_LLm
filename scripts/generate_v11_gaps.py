def _load_old_firsts():
    old = set()
    for f in ["iraqi_v10_corrective.jsonl", "iraqi_v10_extraction.jsonl",
              "iraqi_v10_items.jsonl", "iraqi_v9_generated.jsonl",
              "iraqi_v9_generated_extra.jsonl", "iraqi_v8_batch_train.jsonl",
              "iraqi_v8_batch_val.jsonl"]:
        p = DATA / f
        if not p.exists():
            continue
        with open(p, encoding="utf-8") as fh:
            for line in fh:
                try:
                    old.add(json.loads(line)["messages"][1]["content"].strip())
                except Exception:
                    pass
    return old


OLD_FIRSTS = _load_old_firsts()
USED_FIRSTS = []


def _is_fresh(text):
    text = text.strip()
    if text in OLD_FIRSTS:
        return False
    for prev in USED_FIRSTS:
        if abs(len(text) - len(prev)) > max(len(text), len(prev)) * 0.3:
            continue
        # نفس المقارنة المتناظرة المستخدمة بالفحص الختامي، بحد أشد (0.85)
        # حتى ما تعبر جملتان تختلفان بالماركة بس.
        r = max(difflib.SequenceMatcher(None, text, prev).ratio(),
                difflib.SequenceMatcher(None, prev, text).ratio())
        if r > 0.85:
            return False
    return True


def claim_first(text):
    """يسجل أول رسالة كمستهلكة."""
    USED_FIRSTS.append(text.strip())


def fresh_price_pair(kinds=None, n=2):
    """يرجع (products, (q, a)) بأول رسالة متفردة مضمونة."""
    for _ in range(4000):
        prods = pick_products(n, kinds)
        q, a = price_pair(prods[0][0], prods[0][1])
        if _is_fresh(q):
            claim_first(q)
            return prods, (q, a)
    raise RuntimeError("تعذر توليد أول رسالة متفردة")


def fresh_opening(build, tries=4000):
    """build() يرجع (products, first_user_text, ...) — يعيد المحاولة حتى التفرد."""
    for _ in range(tries):
        result = build()
        first = result[1]
        if _is_fresh(first):
            claim_first(first)
            return result
    raise RuntimeError("تعذر توليد أول رسالة متفردة")


