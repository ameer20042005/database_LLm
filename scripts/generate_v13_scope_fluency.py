def gen_fluency():
    """ثلث الأمثلة مع system — يقرّب نسبة رسالة النظام من التقييم (كانت
    60.4% تدريب مقابل 33.6% تقييم).

    الدور الثاني والثالث يُسحبان من **أي** مجموعة طلاقة لا من مجموعة
    الفئة نفسها. سببان:
      • المحادثة الحقيقية تخلط: تحية ثم سالفة ثم مثل. حصر المحادثة
        بمجموعة وحدة يولّد نمطاً مصطنعاً (سؤال تحية يتبعه سؤال تحية).
      • التنويع الزوجي داخل مجموعة وحدة محدود بـn×(n−1) — مجموعة بـ18
        زوج تعطي 306 محادثة كحد أقصى، وهذا سقف الفئة مهما رُفع الهدف.
    الفئة تُحدَّد بالدور الأول لأنه هو اللي يميز الغرض.
    """
    out = []
    pool = [(c, p) for c, p, _ in FLUENCY_SETS]
    for cat, pairs, target in FLUENCY_SETS:
        seen = set()
        for n in range(target):
            i = n % len(pairs)
            q, a = pairs[i]
            # المتابعات من أي مجموعة — يكسر سقف n×(n−1)
            c2, p2 = pool[(n // len(pairs) + 1) % len(pool)]
            j = (n * 7 + i) % len(p2)
            c3, p3 = pool[(n // len(pairs) + 3) % len(pool)]
            k = (n * 13 + i) % len(p3)
            sig = (i, id(p2), j, k, n % 3, n % 4)
            if sig in seen:
                continue
            seen.add(sig)
            msgs = []
            use_sys = n % 3 == 2
            if use_sys:
                msgs.append({"role": "system", "content": CHAT_SYSTEM})
            msgs += [{"role": "user", "content": q},
                     {"role": "assistant", "content": a}]
            q2, a2 = p2[j]
            msgs += [{"role": "user", "content": q2},
                     {"role": "assistant", "content": a2}]
            if n % 4 == 0:                 # ربع الأمثلة بثلاثة أدوار
                q3, a3 = p3[k]
                if q3 not in (q, q2):
                    msgs += [{"role": "user", "content": q3},
                             {"role": "assistant", "content": a3}]
            out.append({"messages": msgs,
                        "category": cat + ("_sys" if use_sys else ""),
                        "dialect": "iraqi_arabic", "source_file": SOURCE})
    return out


