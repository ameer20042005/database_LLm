def gen_offtopic(n_per_topic=3000):
    """التنويع **توافيقي** لا تكراري: كل مثال = (سؤال × جواب × كتالوج ×
    مسار ضغط) مختلف. التكرار البسيط (سؤال i%len) يولّد نسخ حرفية ويسقط
    بفحص الازدواج — والأخطر أنه يعلّم حفظ الجملة لا مبدأ حدود الاختصاص."""
    out = []
    for topic, qs, answers in OFFTOPIC_SETS:
        combos = [(q, a) for q in qs for a in answers]
        random.shuffle(combos)
        for i in range(min(n_per_topic, len(combos) * 20)):
            q, a = combos[i % len(combos)]
            if topic == "personal" and any(m in q for m in DISTRESS_MARK):
                a = PERS_A_DISTRESS[i % len(PERS_A_DISTRESS)]
            msgs = [{"role": "system", "content": sys_msg()},
                    {"role": "user", "content": q},
                    {"role": "assistant", "content": a}]
            # ثلثا الأمثلة فيها ضغط متابعة — تعليم الصمود لا الرفض لمرة
            # وحدة. مسار الضغط يتنوع بدوره حتى ما يصير قالب ثابت.
            if i % 3 != 2:
                msgs.append({"role": "user", "content": PRESSURE[i % len(PRESSURE)]})
                hold = HOLD[(i // 2) % len(HOLD)]
                if i % 4 == 0:
                    hold += " " + BACK[i % len(BACK)]
                msgs.append({"role": "assistant", "content": hold})
            out.append({"messages": msgs, "category": "off_topic_refusal_general",
                        "subtype": topic, "dialect": "iraqi_arabic",
                        "source_file": SOURCE})
    return out


