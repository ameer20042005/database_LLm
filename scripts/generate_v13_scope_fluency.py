def gen_qa(per_cat=95):
    out = []
    for cat, pairs in QA.items():
        # زوج مختلف × كتالوج مختلف = تنويع توافيقي بدل التكرار
        combos = [(i, j) for i in range(len(pairs)) for j in range(len(pairs))
                  if i != j]
        random.shuffle(combos)
        for n in range(min(per_cat, len(combos))):
            i, j = combos[n % len(combos)]
            q, a = pairs[i]
            msgs = [{"role": "system", "content": sys_msg()},
                    {"role": "user", "content": q},
                    {"role": "assistant", "content": a}]
            q2, a2 = pairs[j]
            msgs += [{"role": "user", "content": q2},
                     {"role": "assistant", "content": a2}]
            out.append({"messages": msgs, "category": cat,
                        "dialect": "iraqi_arabic", "source_file": SOURCE})
    return out


