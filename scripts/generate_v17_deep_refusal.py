def gen_pattern_c(n):
    """امتناعان متتاليان داخل زخم البيع — الأصعب.

    الموديل لازم يمتنع مرتين بلا ما ينهار للاعتذار المتكرر ولا ينكسر
    للاختراع بالمرة الثانية تحت ضغط «ما تعرف شي؟».
    """
    PRESS = ["يعني ما تعرف شي عن البضاعة اللي تبيعها؟",
             "شلون تبيع وما تعرف التفاصيل؟",
             "طيب شنو تعرف عنه؟", "اي معلومة عندك عنه اصلاً؟"]
    PRESS_A = ["اللي مكتوب عندي أنطيك اياه بثقة عيني: {p} بـ{v} دينار. "
               "واللي مو مكتوب ما أخمّنه — أتأكد وأرجعلك بيه",
               "أعرف السعر والموديل مضبوط: {p} بـ{v} دينار. "
               "الباقي أتأكدلك بيه بدل ما أگلك شي غلط",
               "عيني اللي بالقائمة أنطيك اياه فوراً — {p} بـ{v} دينار. "
               "والباقي أسأل وأرد عليك، هذا أحسن من التخمين"]
    out = []
    for _ in range(n):
        (p1, v1), (p2, v2) = random.sample(PRODUCTS, 2)
        sysm = SYS.format(p1=p1, v1=money(v1), p2=p2, v2=money(v2))
        (t1, g1, q1), (t2, g2, q2) = random.sample(GAP_Q, 2)
        _d1, _used = defer(t1, g1)
        _d2, _ = defer(t2, g2, exclude=_used)   # ما يعيد نفس الصيغة
        msgs = [
            {"role": "system", "content": sysm},
            {"role": "user", "content": random.choice(OPEN_U).format(p=p1)},
            {"role": "assistant",
             "content": random.choice(OPEN_A).format(p=p1, v=money(v1))},
            {"role": "user", "content": random.choice(BARG_U)},
            {"role": "assistant", "content": random.choice(BARG_A)},
            {"role": "user", "content": q1},
            {"role": "assistant", "content": _d1},
            {"role": "user", "content": q2},
            {"role": "assistant", "content": _d2},
            {"role": "user", "content": random.choice(PRESS)},
            {"role": "assistant",
             "content": random.choice(PRESS_A).format(p=p1, v=money(v1))},
        ]
        out.append(rec(msgs))
    return out


def main():
    rows, seen = [], set()
    plan = [(gen_pattern_a, 340), (gen_pattern_b, 300), (gen_pattern_c, 260)]
    for fn, n in plan:
        made = fn(int(n * 2.2))
        keep = []
        for r in made:
            k = json.dumps(r["messages"], ensure_ascii=False, sort_keys=True)
            if k in seen:
                continue
            seen.add(k)
            keep.append(r)
        rows.extend(keep[:n])

    random.shuffle(rows)
    p = DATA / "iraqi_v17_deep_refusal.jsonl"
    with p.open("w", encoding="utf-8") as fh:
        for r in rows:
            fh.write(json.dumps(r, ensure_ascii=False) + "\n")

    # ── تحقق: الامتناع فعلاً عميق؟ ──
    import re
    DEFER = re.compile(r"أتأكد|اتأكد|ما مكتوب|ما موضحة|ما مدوّنة|ما عندي")
    depths = []
    for r in rows:
        ai = [i for i, m in enumerate(r["messages"]) if m["role"] == "assistant"]
        for i in ai:
            if DEFER.search(r["messages"][i]["content"]):
                depths.append(len([j for j in ai if j < i]))
    deep = sum(1 for d in depths if d >= 2)
    print("=" * 62)
    print("v17 — الامتناع داخل زخم البيع")
    print("=" * 62)
    print(f"  المحادثات            {len(rows):>6,}")
    print(f"  أدوار الامتناع       {len(depths):>6,}")
    print(f"  منها بعمق 2+ رد      {deep:>6,} ({100*deep/max(len(depths),1):.1f}%)")
    print(f"  متوسط العمق          {sum(depths)/max(len(depths),1):>6.1f} رد")
    print(f"\n  📁 {p.name}")


if __name__ == "__main__":
    main()
