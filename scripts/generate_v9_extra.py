NUM_RE = re.compile(r'\d[\d,\.]*')
FUSHA = ["يمكنني", "بالتأكيد", "يسعدني", "سوف ", "هل ترغب", "في شنو"]


def nums_of(text):
    text = re.sub(r'(\d+)\s*(?:ألف|الف)', lambda m: f"{m.group(1)},000", text)
    return {n.rstrip('.,') for n in NUM_RE.findall(text)}


def validate():
    errors = []
    firsts = []
    old = set()
    for fname in ["iraqi_v9_generated.jsonl", "iraqi_v8_batch_train.jsonl",
                  "iraqi_v8_batch_val.jsonl"]:
        fp = DATA / fname
        if fp.exists():
            with open(fp, encoding="utf-8") as f:
                for line in f:
                    try:
                        old.add(json.loads(line)["messages"][1]["content"].strip())
                    except Exception:
                        pass
    for idx, c in enumerate(CONVS, 1):
        msgs = c["messages"]
        catalog_nums = nums_of(msgs[0]["content"])
        user_nums = set()
        for m in msgs[1:]:
            if m["role"] == "user":
                user_nums |= nums_of(m["content"])
                continue
            for n in nums_of(m["content"]):
                if n in catalog_nums or n in user_nums:
                    continue
                if ',' not in n and '.' not in n and len(n) <= 2:
                    continue
                errors.append(f"{idx} ({c['category']}): رقم مخترع '{n}': {m['content'][:60]}")
            for f in FUSHA:
                if f in m["content"]:
                    errors.append(f"{idx}: فصحى ممنوعة '{f}'")
        first = msgs[1]["content"].strip()
        if first in old:
            errors.append(f"{idx}: أول رسالة مكررة من v8/v9: {first[:50]}")
        if first in firsts:
            errors.append(f"{idx}: أول رسالة مكررة داخلياً: {first[:50]}")
        firsts.append(first)
    return errors


def main():
    errs = validate()
    if errs:
        for e in errs:
            print("❌", e)
        sys.exit(1)
    out = DATA / "iraqi_v9_generated_extra.jsonl"
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        for c in CONVS:
            f.write(json.dumps(c, ensure_ascii=False) + "\n")
    from collections import Counter
    print(f"✅ {out.name}: {len(CONVS)} محادثة")
    for cat, n in sorted(Counter(c["category"] for c in CONVS).items()):
        print(f"   {cat:<25} {n}")


if __name__ == "__main__":
    main()
