# «نعم» و«قد» يحتاجان سياقاً — الاستبدال الأعمى يكسر المعنى:
#   «نعم» بأول الجملة = «إي»، لكن «نعم الأخ» تعبير مدح ما ينلمس.
#   «قد» قبل فعل = «ممكن»، لكن «قدم» و«قدر» ما إلهن علاقة (محمية
#   بحدود الكلمة أصلاً)، و«قد» بمعنى «لقد» تختلف.
CONTEXTUAL = [
    (r"(?<![ء-ي])نعم(?=[\s،,]+(?:عيني|خويه|والله|أكيد))", "إي"),
    (r"^نعم(?=[\s،,])", "إي"),
    (r"(?<![ء-ي])نعم(?=[\s،,]*$)", "إي"),
    (r"(?<![ء-ي])قد(?=\s+(?:يعجبك|تلاقي|يكون|تحتاج|ينفع|يصير|يفيدك))",
     "ممكن"),
]

# حرف عربي = الحروف فقط، لا علامات الترقيم العربية.
# النطاق الكامل [؀-ۿ] يشمل «؟» (U+061F) و«،» (U+060C)، فيصير lookahead
# يحسبهن حروفاً ويمنع المطابقة: «شلون شلونك؟» ما تنمسك أبداً.
AR = r"[ء-ي٠-٩ٮ-ۓ۰-۹]"
COMPILED = [(re.compile(f"(?<!{AR}){re.escape(p)}(?!{AR})"), r)
            for p, r in PHRASES]
COMPILED_CTX = [(re.compile(p, re.M), r) for p, r in CONTEXTUAL]

# صفر مساس بالردود اللي فيها بنية آلية
FORBIDDEN = ("[TOOL_CALL]", "[ORDER_READY]", "{", "}")

TARGETS = ["iraqi_train_v8_part*.jsonl", "iraqi_v9_generated*.jsonl",
           "iraqi_v10_*.jsonl", "iraqi_v11_gaps.jsonl", "iraqi_v12_order.jsonl",
           "iraqi_v13_scope.jsonl", "iraqi_v14_expand.jsonl",
           "iraqi_v15_behavioral.jsonl", "iraqi_val_v8.jsonl",
           "iraqi_val_v13.jsonl"]


def iraqify(text, stats):
    if any(f in text for f in FORBIDDEN):
        return text
    out = text
    for rx, rep in COMPILED:
        new, n = rx.subn(rep, out)
        if n:
            stats[rx.pattern.split("(?<!")[-1][:24] or rep] += n
            out = new
    for rx, rep in COMPILED_CTX:
        new, n = rx.subn(rep, out)
        if n:
            stats["نعم/قد (سياقي)"] += n
            out = new
    return out


def main():
    files = [f for g in TARGETS for f in sorted(DATA.glob(g))]
    assert files, "ملفات المصدر غير موجودة"

    BACKUP.mkdir(exist_ok=True)
    for f in files:
        if not (BACKUP / f.name).exists():
            shutil.copy2(f, BACKUP / f.name)
    print(f"✅ نسخة احتياطية بـ{BACKUP.name}/ ({len(files)} ملف)")

    stats, touched, total = Counter(), 0, 0
    for f in files:
        rows = [json.loads(l) for l in f.open(encoding="utf-8")]
        for r in rows:
            for t in r["messages"]:
                # رسالة النظام تعليمات للموديل لا حچي زبون — تعريقها
                # يغيّر قالب التأسيس نفسه («الموجود حالياً» → «الموجود
                # هسه» بـ13,544 رسالة)، وهذا تعديل ببنية المطالبة مو
                # باللهجة. اللهجة تخص أدوار user/assistant.
                if t["role"] == "system":
                    continue
                total += 1
                new = iraqify(t["content"], stats)
                if new != t["content"]:
                    t["content"] = new
                    touched += 1
        with f.open("w", encoding="utf-8") as fh:
            for r in rows:
                fh.write(json.dumps(r, ensure_ascii=False) + "\n")

    print(f"\nرسائل معدَّلة: {touched:,} من {total:,} "
          f"({100*touched/total:.2f}%)")
    print(f"\n{'الاستبدال':<28}{'العدد':>9}")
    for k, n in stats.most_common(30):
        print(f"  {k:<26}{n:>9,}")
    print(f"  {'المجموع':<26}{sum(stats.values()):>9,}")
    print(f"\n↩️ للتراجع: cp {BACKUP.name}/*.jsonl data/")


if __name__ == "__main__":
    main()
