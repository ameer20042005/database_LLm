# -*- coding: utf-8 -*-
"""
v20 — حقن هوية البائع بردود الرفض الموجودة.

═══════════════════════════════════════════════════════════════
المشكلة
═══════════════════════════════════════════════════════════════
`generate_v20` يضيف 420 مثالاً جديداً بهوية صريحة، بس الداتا الموجودة
فيها **4,322 رد رفض خارج النطاق، 676 بس (16%) تذكر إنه بائع**. الباقي
يرفض بلا ما يوضّح ليش:

    «ما إلي بهاي الأمور عيني»          ← رفض جاف، ما يوضّح السبب
    «هذا مو مجالي، تأمر بشي؟»          ← أحسن، بس بلا هوية صريحة

نفس درس v16/v19: إضافة الصح فوق الباقي تخلي الموديل يشوف النمطين
بنفس الوزن. فالحقن على الموجود ضروري.

═══════════════════════════════════════════════════════════════
التنفيذ
═══════════════════════════════════════════════════════════════
الردود اللي **ما تذكر** الهوية أصلاً يُضاف لها تعريف قصير بالبداية.
الردود اللي تذكرها ما تنلمس (تفادي الحشو).

**الطبقة الطبية مستثناة من التعديل الأسلوبي**: ردودها مضبوطة بقاعدة
صارمة (إحالة صريحة، صفر منتج)، وأي حقن تلقائي ممكن يكسرها. بدلها
نضيف الهوية بصيغة تحافظ على الإحالة.
"""
import json
import random
import re
import sys
from collections import Counter
from pathlib import Path

sys.stdout.reconfigure(encoding="utf-8")
random.seed(20260801)

SRC = Path(__file__).resolve().parent.parent / "data" / "v16"

OFF_CATS = {"off_topic_refusal_general", "off_topic_general_polite"}

# ⚠️ الأنماط لازم تكون **واسعة**: أول تشغيلة استعملت قوائم ضيقة فحقنت
# الهوية على ردود أصلاً تذكرها بصيغة ثانية، وطلع:
#   «أني متخصص بالمبيعات عيني، ... بس أنا بياع بس عيني»
#   «تخصصي البيع بس، هذا يحتاج عالم دين، مو بياع مثلي»
# يعني تعريف مكرر مرتين وثلاث. أي إشارة للبيع/المحل/الشغل تُحسب هوية.
SELLER = re.compile(
    r"متخصص بالمبيعات|بائع|بياع|شغلي بيع|تخصصي البيع|موظف مبيعات|"
    r"أفهم بالأجهزة|إحنه محل|احنه محل|شغلي بالمحل|أني بالبيع|"
    r"شغلي|مو شغلي|خارج شغلي|بشغل المحل|مو مجالي|اختصاصي|"
    r"مالتي|مو مالتي|بالمحل")
# مختص منصوح بيه — أي إحالة لجهة مختصة تُحسب، حتى «أهل الطب» و«عالم دين»
EXPERT = re.compile(
    r"مختص|طبيب|دكتور|محامي|مهندس|محاسب|مرشد|كهربائي|ميكانيكي|"
    r"رجل دين|عالم دين|أهل الاختصاص|أهل الطب|أهل العلم|النشرة|"
    r"صيدلي|صيدلية|عيادة|المحكمة|اسأل أهل|يسألون أهل")

IDENT_PREFIX = [
    "أني متخصص بالمبيعات عيني، ",
    "صراحةً شغلي بيع، ",
    "أني بائع عيني، ",
    "تخصصي البيع بس، ",
    "أني موظف مبيعات، ",
]
# نصيحة عامة بمختص لمن الرد ما يذكر واحداً
EXPERT_TAIL = [
    " — الأفضل تسأل مختص بهاي",
    " — أهل الاختصاص أدرى بيها",
    " — استشير واحد مختص وهو يفيدك",
]


def inject(text):
    """يضيف الهوية إذا مو موجودة، والنصيحة بمختص إذا مو موجودة.

    الحقن **محافظ**: إضافة وحدة بالأكثر لكل رد. أول تشغيلة أضافت
    الاثنين معاً على 21,439 رداً فطلع حشو («صراحةً شغلي بيع، ... —
    أهل الاختصاص أدرى بيها» على رد أصلاً يگول «سؤال لأهل الطب»).
    """
    has_id = bool(SELLER.search(text))
    has_exp = bool(EXPERT.search(text))
    if has_id and has_exp:
        return text, False

    out = text
    if not has_id:
        out = random.choice(IDENT_PREFIX) + out
    elif not has_exp:
        # الهوية موجودة والنصيحة ناقصة -> ذيل بس
        out = out.rstrip(" .،") + random.choice(EXPERT_TAIL)

    out = re.sub(r"\s{2,}", " ", out).strip()
    # نداءان متجاوران نتجا عن الحقن
    out = re.sub(r"(عيني|خوية)\s*،?\s+(عيني|خوية)\b", r"\1", out)
    return out, out != text


def main():
    stats = Counter()
    for f in sorted(SRC.glob("*.jsonl")):
        rows = []
        for line in f.open(encoding="utf-8"):
            d = json.loads(line)
            if d.get("category") not in OFF_CATS:
                rows.append(d)
                continue
            msgs = []
            for m in d["messages"]:
                if m["role"] != "assistant":
                    msgs.append(m)
                    continue
                t = m["content"]
                stats["off_topic_turns"] += 1
                if SELLER.search(t) and EXPERT.search(t):
                    stats["already_ok"] += 1
                    msgs.append(m)
                    continue
                t2, ok = inject(t)
                if ok:
                    stats["injected"] += 1
                msgs.append({**m, "content": t2})
            d["messages"] = msgs
            rows.append(d)

        with f.open("w", encoding="utf-8") as fh:
            for r in rows:
                fh.write(json.dumps(r, ensure_ascii=False) + "\n")

    print("=" * 58)
    print("v20 — هوية البائع بردود الرفض")
    print("=" * 58)
    for k, v in stats.most_common():
        print(f"  {k:<24}{v:>8,}")


if __name__ == "__main__":
    main()
